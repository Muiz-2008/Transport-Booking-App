export const getBusesByRoute = (from, to) => {
  if (!from && !to) return buses
  return buses.filter(b => {
    const matchFrom = !from || b.from.toLowerCase() === from.toLowerCase()
    const matchTo = !to || b.to.toLowerCase() === to.toLowerCase()
    return matchFrom && matchTo
  })
}

export const getBusById = (id) => buses.find(b => b.id === id)
